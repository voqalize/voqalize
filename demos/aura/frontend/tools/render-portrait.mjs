/**
 * Render one still frame of Aria's face to `src/aria-portrait.svg`.
 *
 * The launcher — the pill in the corner of a bank page nobody has asked for help
 * on yet — wears a *picture* of Aria, not a running rig. A face that blinks and
 * breathes at 52 px is a distraction on a page about interest certificates, and
 * the live rig draws a 4:3 bust that has to be scaled and clipped to fit a round
 * badge, which keeps the head and throws away everything that said "person".
 *
 * The public entry points cannot produce a still: `createAvatar` documents
 * `client` as "Required, and not nullable" and `<Avatar>` renders nothing until
 * it has one. The *renderer* underneath never hears about a client, though —
 * `@voqalize/avatar/internal` exports it as `createSvgAvatar({mount, face, …})`
 * — and the avatar repo's own `mount.smoke.test.ts` already mounts it under
 * jsdom. This is that test with the assertions swapped for a serialise.
 *
 * Run it when the face, the pose or the crop should change — the output is
 * committed, so this is not part of any build:
 *
 *     pnpm add -D jsdom
 *     node tools/render-portrait.mjs src/aria-portrait.svg
 *     pnpm remove jsdom
 *
 * jsdom is deliberately not a dependency: it is five megabytes to install on
 * every CI web build for an asset that changes about once a year.
 */
import { writeFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const out = process.argv[2];
if (!out) throw new Error('usage: node tools/render-portrait.mjs <out.svg>');

const dom = new JSDOM('<!doctype html><body></body>');
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.Node = dom.window.Node;
globalThis.Element = dom.window.Element;
globalThis.SVGElement = dom.window.SVGElement;
globalThis.performance ??= dom.window.performance;
// jsdom implements neither, and the rig calls them unconditionally on teardown.
// `manual: true` means the loop never asks for a frame; this is only insurance.
globalThis.requestAnimationFrame = (cb) => setTimeout(() => cb(Date.now()), 16);
globalThis.cancelAnimationFrame = (id) => clearTimeout(id);

const { createSvgAvatar } = await import('@voqalize/avatar/internal');
const { myna } = await import('@voqalize/avatar/faces/myna');

const mount = document.createElement('div');
document.body.appendChild(mount);

// The pose: looking down the barrel of the camera, warm, hands out of frame. A
// frame-edge hand at badge size is a smudge.
const avatar = createSvgAvatar({ mount, face: myna, manual: true, hand: false });
avatar.setState('LISTENING');
avatar.setGaze('USER');
avatar.setEmotion('warm', 0.65);

// Settle. The mixer eases toward its target, so frame one lands mid-transition
// out of the construction pose; two seconds at 60 Hz is comfortably at rest.
for (let i = 0; i < 120; i++) avatar.step(1 / 60);

const svg = avatar.svg;
svg.removeAttribute('role');
svg.removeAttribute('aria-label');
svg.setAttribute('xmlns', 'http://www.w3.org/2000/svg');

// Square the camera. The rig authors a 4:3 call frame (`CALL_CAMERA`), which is
// right for the tile's video area and wrong for a round badge: a circle
// inscribed in a landscape box keeps the ceiling and cuts the hair. Crop the
// middle square instead — full crown-to-shoulder height, sides trimmed — so the
// launcher needs no transform and no overflow trickery.
const [vx, vy, vw, vh] = svg.getAttribute('viewBox').split(/\s+/).map(Number);
svg.setAttribute('viewBox', `${vx + (vw - vh) / 2} ${vy} ${vh} ${vh}`);
svg.setAttribute('width', '256');
svg.setAttribute('height', '256');

const header = `<!--
  Aria's portrait — one still frame of @voqalize/avatar's \`myna\` rig: pose
  LISTENING, gaze USER, emotion warm at 0.65, hand off, settled two seconds,
  cropped to the middle square of the call camera.

  Generated by tools/render-portrait.mjs, which explains why. Regenerate rather
  than editing this by hand.
-->
`;
writeFileSync(out, header + svg.outerHTML + '\n');
console.log('viewBox:', svg.getAttribute('viewBox'), '| bytes:', svg.outerHTML.length);
