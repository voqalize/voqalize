def test_career_and_programme_pages_take_their_templates_shape() -> None:
    """One template record holds every career page's sections and tabs; it is
    not a page itself, and each career's page shows its tabs by their labels."""
    assert not [key for key in K.pages if key.endswith("*")]
    psicologia = K.page("/carreras/psicologia/")
    assert psicologia is not None
    assert "Requisitos y Aranceles" in psicologia.toggles
    assert "Datos Académicos" in psicologia.headings
    programme = K.page("postgrados.uahurtado.cl/programa/magister-intervencion-psicosocial/")
    assert programme is not None and "Requisitos y Valores" in programme.toggles
    homes = {K.page(f"https://{h}/").title for h in kb.HOSTS}  # type: ignore[union-attr]
    assert len(homes) == 3
