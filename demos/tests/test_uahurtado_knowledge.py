"""The committed UAH knowledge: it loads, it carries no figure that changes, and
the brain's finders read it the way a visitor speaks.

Fees, dates, PAES minimums and weights are read live off the page in the
visitor's browser, never from here: the site disagrees with itself about them
(/aranceles/ is last year's), and a figure in the knowledge would be said as
if it were today's. So every layer is scanned for one.

Run: ``cd demos && uv run pytest tests/test_uahurtado_knowledge.py``
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
from voqalize_demos.discovery import discover

discover()

from voqalize_demos._loaded.uahurtado import brain as uah  # noqa: E402
from voqalize_demos._loaded.uahurtado import knowledge as kb  # noqa: E402

K = kb.KNOWLEDGE
ROOT = kb.ROOT

#: What a figure that changes looks like, in Spanish as the site writes it.
_FIGURES = {
    "a peso amount": r"\$\s?\d{1,3}(?:\.\d{3})+|\$\s?\d{4,}",
    "an amount in UF": r"\b\d+(?:[.,]\d+)?\s*UF\b",
    "a numeric date": r"\b\d{1,2}[/-]\d{1,2}[/-](?:19|20)\d\d\b|\b20\d\d-\d\d-\d\d\b",
    "a day of a month": (
        r"\b\d{1,2}(?:º|°)? (?:de )?(?:enero|febrero|marzo|abril|mayo|junio|julio|agosto|"
        r"septiembre|octubre|noviembre|diciembre)\b"
    ),
    "a PAES weight": (
        r"\b(?:NEM|Ranking|Lectora|Matem[aá]tica|M1|M2|Historia|Ciencias)\b[^.\n]{0,25}?"
        r"\b\d{1,2}\s?%(?!\s*(?:superior|online|de los|de las|más))"
    ),
    "a minimum score": r"\bm[ií]nimo[^.\n]{0,40}?\b[1-9]\d{2}\b(?!\s*(?:horas|créditos|SCT))",
    "an arancel or matrícula figure": r"\b(?:Arancel|Matr[ií]cula)\b[^.\n]{0,20}?\$",
}


def _knowledge_texts() -> list[tuple[str, str]]:
    """Every knowledge file the brain reads, as (name, text)."""
    files = [
        ROOT / "L1.md",
        *sorted((ROOT / "L2").rglob("*.md")),
        *sorted((ROOT / "L3").glob("*.json")),
    ]
    return [(str(f.relative_to(ROOT)), f.read_text(encoding="utf-8")) for f in files if f.exists()]


#: What reads like a figure and is not one: the day the crawl ran (provenance,
#: not a fact he says), and an admission route named after its own threshold.
_NOT_FIGURES = re.compile(
    r"(?:crawled|generated by build\.py on|\"crawled\":)\s*\"?20\d\d-\d\d-\d\d"
    r"|NEM 30%\s*o\s+superior",
    re.IGNORECASE,
)


def _figures(text: str) -> list[tuple[str, str]]:
    text = _NOT_FIGURES.sub(" ", text)
    found: list[tuple[str, str]] = []
    for name, rx in _FIGURES.items():
        found += [(name, m.group(0)) for m in re.finditer(rx, text, re.IGNORECASE)]
    return found


def test_the_figure_check_catches_figures_and_lets_words_through() -> None:
    assert _figures("Matrícula $277.456 Arancel anual $7.167.421 Titulación 11 UF")
    assert _figures("Postulación desde el 01-10-2026, hasta el 31 de marzo")
    assert _figures("NEM 10%, Ranking 20%; puntaje mínimo 458")
    assert not _figures("Psicología dura 10 semestres, en jornada diurna, 100% online.")
    assert not _figures("Gratuidad para el 60% de menores ingresos. El 10% superior de notas.")
    assert not _figures("Vías: NEM 30% o superior. Crawled 2026-10-22.")
    assert _figures("Deben contar con puntaje ranking mínimo de 550 puntos.")


@pytest.mark.parametrize(
    ("name", "text"), _knowledge_texts(), ids=[n for n, _ in _knowledge_texts()]
)
def test_no_figure_that_changes_is_in_the_knowledge(name: str, text: str) -> None:
    assert _figures(text) == [], f"{name}: {_figures(text)[:8]}"


def test_the_committed_knowledge_loads_in_full() -> None:
    assert len(K.careers) == 50
    assert len(K.programs) == 82
    assert len(K.pages) >= 150
    hosts = {kb.host_of(key) for key in K.pages}
    assert hosts == {kb.ADMISION, kb.POSTGRADOS, kb.WWW}
    for topic in ("admision", "becas-y-beneficios", "gratuidad", "campus-y-sedes", "postgrado"):
        assert topic in K.topics, topic
    assert set(kb.TOPIC_IDS) == set(K.topics)
    assert K.l1.strip()


def test_every_topic_names_its_sources() -> None:
    for topic in K.topics.values():
        assert topic.text.lstrip().startswith("# "), topic.id
        assert "Sources:" in topic.text[:600], topic.id


def test_every_career_and_programme_is_a_page_he_can_open() -> None:
    for c in K.careers.values():
        assert c.key.startswith(f"{kb.ADMISION}/carreras/"), c.slug
        assert K.page(c.url) is not None, c.slug
        assert c.faculty, c.slug
        assert set(c.tab_labels) <= set(kb.CAREER_TAB_LABELS.values()), c.slug
        assert not c.malla_pdf or kb.is_link_url(c.malla_pdf), c.slug
    for p in K.programs.values():
        assert p.key.startswith(f"{kb.POSTGRADOS}/programa/"), p.slug
        assert K.page(p.url) is not None, p.slug
        assert p.type in {"magister", "doctorado", "diplomado", "postitulo", "otro"}, p.slug


def test_every_page_the_brain_routes_to_was_crawled() -> None:
    for _, path in uah._ASKED_PAGES:
        key = kb.page_key(path)
        assert key is not None and key in K.pages, path


