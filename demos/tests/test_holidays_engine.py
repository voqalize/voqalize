"""Wanderloom's engine and data: the committed files are current, and the rules
CONTRACT.md writes down hold.

``data/inventory.json`` is generated by ``data/build_inventory.py`` and
``data/engine_cases.json`` by ``backend/engine.py``; the page runs the cases in
vitest against its own engine, so a stale file would let the two drift.

Run: ``cd demos && uv run pytest tests/test_holidays_engine.py``
"""

from __future__ import annotations

import importlib.util
import json
from datetime import date
from pathlib import Path

from voqalize_demos.discovery import discover

discover()

from voqalize_demos._loaded.holidays import engine as eng  # noqa: E402

DATA = Path(__file__).resolve().parent.parent / "holidays" / "data"


def test_the_inventory_is_current() -> None:
    spec = importlib.util.spec_from_file_location("build_inventory", DATA / "build_inventory.py")
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    built = json.loads(json.dumps(module.build(), ensure_ascii=False))
    assert built == json.loads((DATA / "inventory.json").read_text()), (
        "inventory.json is stale: run `uv run python holidays/data/build_inventory.py` from demos/"
    )


def test_the_engine_cases_are_current() -> None:
    assert eng.cases() == json.loads((DATA / "engine_cases.json").read_text()), (
        "engine_cases.json is stale: run engine.write_cases()"
    )


def test_every_origin_reaches_every_destination_and_every_id_is_unique() -> None:
    inv = eng.INVENTORY
    for o in inv["origins"]:
        for d in inv["destinations"]:
            assert [
                f for f in inv["flights"] if f["origin"] == o["id"] and f["destination"] == d["id"]
            ]
    for kind in (eng.FLIGHTS, eng.HOTELS, eng.ACTIVITIES, eng.CITIES):
        assert kind
    ids = [h["id"] for c in eng.CITIES.values() for h in c["hotels"]]
    assert len(ids) == len(set(ids))
    acts = [a["id"] for c in eng.CITIES.values() for a in c["activities"]]
    assert len(acts) == len(set(acts))
    assert len(inv["destinations"]) == 9


def test_money_is_indian_grouping() -> None:
    assert eng.money(125000) == "₹1,25,000"
    assert eng.money(12345678) == "₹1,23,45,678"
    assert eng.money(999) == "₹999"


def test_a_month_starts_on_the_first_friday_from_the_tenth_a_week_out() -> None:
    today = date(2026, 11, 18)
    assert eng.month_start(12, today) == date(2026, 12, 11)
    assert eng.month_start(11, today) == date(2027, 11, 12)  # the 13th of Nov 2026 is too soon
    assert eng.month_start(2, today).weekday() == 4


def test_travel_days_have_only_the_evening_and_ages_and_weekdays_are_kept() -> None:
    t = eng.Trip(from_city="DEL", destination="bali", start_date="2027-02-12", nights=6, adults=2)
    t.split = [3, 3]
    kinds = [d.kind for d in eng.days(t)]
    assert kinds == ["arrival", "full", "full", "transfer", "full", "full", "departure"]
    assert eng.can_add(t, "ubud-terraces", 1) == "day 1 is a travel day, with only the evening free"
    assert eng.can_add(t, "ubud-kecak", 1) is None
    assert eng.can_add(t, "seminyak-surf", 2) is not None  # day 2 is in Ubud
    t.kids = [5]
    assert eng.can_add(t, "ubud-batur-trek", 2) == "Mount Batur sunrise trek is for ages 10 and up"
    goa = eng.Trip(from_city="DEL", destination="goa", start_date="2027-01-08", nights=4, adults=2)
    goa.split = [2, 2]
    # 9 Jan 2027 is a Saturday: the market runs; the 10th it does not.
    assert eng.can_add(goa, "goa-night-market", 2) is None
    goa.split = [3, 1]
    assert "does not run on Sun" in (eng.can_add(goa, "goa-night-market", 3) or "")


def test_prices_follow_the_written_rules() -> None:
    t = eng.Trip(
        from_city="BOM",
        destination="dubai",
        start_date="2026-12-11",
        nights=4,
        adults=3,
        kids=[7, 1],
    )
    t.split = [4]
    t.flight_id = "BOM-dubai-1"
    f = eng.FLIGHTS["BOM-dubai-1"]
    adult = eng.round10(f["fare_adult"] * 118 / 100)  # December
    child = eng.round10(adult * 75 / 100)
    assert eng.flight_price(t, f) == (adult, adult * 3 + child + 3500)
    t.hotels["dubai"] = ("marina-sail", "city")
    assert eng.rooms(t) == 2
    assert eng.hotel_price(t, "dubai", "marina-sail", "city") == 13600 * 4 * 2
    assert [leg.mode for leg in eng.transfer_legs(t)] == ["private SUV", "private SUV"]
    p = eng.price(t)
    assert p.gst == eng.half_up((p.hotels + p.transfers + p.activities) * 5 / 100)
    assert p.total == p.flights + p.hotels + p.transfers + p.activities + p.gst


def test_a_package_over_budget_moves_to_cheaper_hotels() -> None:
    t = eng.Trip(
        from_city="DEL",
        destination="bali",
        start_date="2027-02-12",
        nights=6,
        adults=2,
        style="honeymoon",
    )
    t.split = [3, 3]
    rich = eng.build_package(t)
    t.budget = eng.price(rich).total - 1
    cheap = eng.build_package(t)
    assert eng.price(cheap).total < eng.price(rich).total
    assert cheap.hotels["ubud"] == ("terrace-lodge", "deluxe")
