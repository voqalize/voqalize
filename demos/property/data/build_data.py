def _km(a: tuple[float, float], b: tuple[float, float]) -> float:
    return round(math.dist(a, b) * KM_PER_UNIT, 1)


def _nearby(city: str, x: float, y: float) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {"office": [], "school": [], "metro": []}
    for pid, name, kind, px, py in PLACES[city]:
        out[kind].append({"id": pid, "name": name, "km": _km((x, y), (px, py))})
    for kind in out:
        out[kind].sort(key=lambda p: p["km"])
    return {"offices": out["office"], "schools": out["school"][:3], "metro": out["metro"][:2]}


def _code(city: str) -> str:
    return next(c["code"] for c in CITIES if c["id"] == city)


